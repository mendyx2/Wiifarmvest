import { Head, router, usePage } from '@inertiajs/react';
import { useState, type FormEvent } from 'react';
import ConfirmDialog from '@/Components/ConfirmDialog';
import Pagination from '@/Components/Pagination';
import { useCopy } from '@/lib/clipboard';
import { useTrans } from '@/lib/i18n';
import { visitWithQuery } from '@/lib/search';
import type { PageProps, Paginated } from '@/types';

type Pin = { id: number; pin: string; amount: string; used: boolean; created: string; usedAgo: string | null; usedBy: string | null };
type Filters = { search: string; status: string };

type Props = PageProps<{
    visa: string;
    price: { amount: string; cur: string; charge: string | null; total: string; enough: boolean };
    stats: { total: number; unused: number; used: number };
    pins: Paginated<Pin>;
    filters: Filters;
    urls: { index: string; generate: string };
}>;

const STEP_STYLE = { width: 28, height: 28, borderRadius: '50%', display: 'flex', alignItems: 'center', justifyContent: 'center', fontSize: '.75rem', fontWeight: 800, flexShrink: 0 } as const;

export default function Epin({ visa, price, stats, pins, filters, urls }: Props) {
    const t = useTrans();
    const { url } = usePage();
    const [values, setValues] = useState<Filters>(filters);
    const [confirming, setConfirming] = useState(false);
    const [busy, setBusy] = useState(false);

    const generate = () =>
        router.post(urls.generate, {}, {
            preserveScroll: true,
            onStart: () => setBusy(true),
            onFinish: () => {
                setBusy(false);
                setConfirming(false);
            },
        });

    const applyFilters = (event: FormEvent) => {
        event.preventDefault();
        visitWithQuery(url, values);
    };

    const steps = [
        { n: 1, bg: '#D1FAE5', fg: '#059669', title: t('Generate a Pin'), text: t(':amount :cur is deducted from your VISA wallet', { amount: price.amount, cur: price.cur }) },
        { n: 2, bg: '#EDE9FE', fg: '#7C3AED', title: t('Share the Pin'), text: t('Copy and send the pin code to another member') },
        { n: 3, bg: '#FEF3C7', fg: '#D97706', title: t('Member activate new Account with this Pin'), text: null },
    ];

    return (
        <div className="epin-page">
            <Head title={t('Recharge Your Wallet')} />

            <div className="epin-stats">
                <Stat tone="green" icon="la-qrcode" label={t('Total Pins')} value={stats.total} sub={t('Generated by you')} />
                <Stat tone="amber" icon="la-dot-circle" label={t('Unused')} value={stats.unused} sub={t('Ready to use')} />
                <Stat tone="slate" icon="la-check-circle" label={t('Used')} value={stats.used} sub={t('Redeemed')} />
            </div>

            <div className="epin-actions">
                <div className="epin-action-card">
                    <div className="epin-action-header">
                        <div className="epin-action-header-icon green">
                            <i className="las la-plus-circle" />
                        </div>
                        <div>
                            <p className="epin-action-title">{t('Generate Pin')}</p>
                            <p className="epin-action-sub text-dark">
                                {t('VISA wallet')} -- {visa}
                            </p>
                        </div>
                    </div>
                    <div className="epin-action-body">
                        <div className="epin-amount-display">
                            <span className="epin-amount-label">{t('Fixed Amount')}</span>
                            <span>
                                <span className="epin-amount-value">{price.amount}</span> <span className="epin-amount-cur">{price.cur}</span>
                            </span>
                        </div>
                        {price.charge && (
                            <p className="epin-charge-note">
                                {t('Plus :charge e-pin charge: :total in total', { charge: price.charge, total: price.total })}
                            </p>
                        )}
                        {!price.enough && <p className="epin-charge-note epin-charge-note--warn">{t('Your VISA wallet does not cover this pin yet.')}</p>}
                        <button type="button" className="epin-btn green" onClick={() => setConfirming(true)} disabled={busy || !price.enough}>
                            <i className="las la-qrcode" /> {t('Generate New Pin')}
                        </button>
                    </div>
                </div>

                <div className="epin-action-card">
                    <div className="epin-action-header">
                        <div className="epin-action-header-icon violet">
                            <i className="las la-info-circle" />
                        </div>
                        <div>
                            <p className="epin-action-title">{t('How It Works')}</p>
                            <p className="epin-action-sub">{t('Share & earn with E-Pins')}</p>
                        </div>
                    </div>
                    <div className="epin-action-body">
                        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
                            {steps.map((step) => (
                                <div key={step.n} style={{ display: 'flex', alignItems: 'flex-start', gap: 10 }}>
                                    <div style={{ ...STEP_STYLE, background: step.bg, color: step.fg }}>{step.n}</div>
                                    <div>
                                        <p style={{ fontSize: '.8rem', fontWeight: 700, color: '#111827', margin: '0 0 2px' }}>{step.title}</p>
                                        {step.text && <p style={{ fontSize: '.72rem', color: '#9CA3AF', margin: 0 }}>{step.text}</p>}
                                    </div>
                                </div>
                            ))}
                        </div>
                    </div>
                </div>
            </div>

            <div className="epin-list-card">
                <div className="epin-list-head">
                    <h6 className="epin-list-title">
                        <i className="las la-list-alt" /> {t('My Generated Pins')}
                    </h6>
                </div>
                <form onSubmit={applyFilters}>
                    <div className="epin-filter">
                        <input type="search" placeholder={t('Search pin...')} value={values.search} onChange={(e) => setValues({ ...values, search: e.target.value })} />
                        <select value={values.status} onChange={(e) => setValues({ ...values, status: e.target.value })} aria-label={t('Status')}>
                            <option value="">{t('All Status')}</option>
                            <option value="0">{t('Unused')}</option>
                            <option value="1">{t('Used')}</option>
                        </select>
                        <button type="submit" className="epin-filter-btn">
                            <i className="las la-filter" /> {t('Filter')}
                        </button>
                    </div>
                </form>

                {pins.data.length === 0 ? (
                    <div className="epin-empty">
                        <div className="epin-empty-icon">
                            <i className="las la-qrcode" />
                        </div>
                        <h6>{t('No pins generated yet')}</h6>
                        <p>{t('Click "Generate New Pin" above to create your first E-Pin.')}</p>
                    </div>
                ) : (
                    pins.data.map((pin) => <PinRow key={pin.id} pin={pin} />)
                )}
            </div>

            <Pagination links={pins.links} />

            <ConfirmDialog
                open={confirming}
                busy={busy}
                question={t('Generate a :amount :cur pin? :total will be taken from your VISA wallet.', { amount: price.amount, cur: price.cur, total: price.total })}
                onConfirm={generate}
                onCancel={() => setConfirming(false)}
            />
        </div>
    );
}

function Stat({ tone, icon, label, value, sub }: { tone: string; icon: string; label: string; value: number; sub: string }) {
    return (
        <div className="epin-stat">
            <div className={`epin-stat-icon ${tone}`}>
                <i className={`las ${icon}`} />
            </div>
            <div>
                <p className="epin-stat-label">{label}</p>
                <p className="epin-stat-value">{value}</p>
                <p className="epin-stat-sub">{sub}</p>
            </div>
        </div>
    );
}

function PinRow({ pin }: { pin: Pin }) {
    const t = useTrans();
    const { copied, copy } = useCopy(2000);

    return (
        <div className="epin-pin-row">
            <div className={`epin-status-dot ${pin.used ? 'used' : 'unused'}`} />
            <div style={{ flex: 1, minWidth: 0 }}>
                <div className="epin-pin-code">{pin.pin}</div>
                <div className="epin-pin-meta">
                    {pin.created}
                    {pin.used && (
                        <>
                            {' '}
                            &bull; {t('Used :ago', { ago: pin.usedAgo ?? '' })} &nbsp; &nbsp; {t('Used By: :user', { user: pin.usedBy ?? '—' })}
                        </>
                    )}
                </div>
            </div>
            <div className="epin-pin-right">
                <span className="epin-amount-chip">{pin.amount}</span>
                <span className={`epin-badge ${pin.used ? 'used' : 'unused'}`}>{pin.used ? t('Used') : t('Unused')}</span>
                {!pin.used && (
                    <button
                        type="button"
                        className={`epin-copy-btn${copied ? ' done' : ''}`}
                        title={t('Copy Pin')}
                        onClick={async () => {
                            if (await copy(pin.pin)) window.notify?.('success', t('Pin copied!'));
                            else window.notify?.('error', t('Failed to copy pin.'));
                        }}
                    >
                        <i className={`las ${copied ? 'la-check' : 'la-copy'}`} />
                    </button>
                )}
            </div>
        </div>
    );
}
